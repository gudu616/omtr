    y = rankdata(col(rs, D))
    xg = rankdata(col(rs, G))
    xc = np.array([1.0 if r["level"] == "L0" else 0.0 for r in rs])
    def r2(X):
        X1 = np.column_stack([np.ones(len(y))] + X)
        coef, *_ = np.linalg.lstsq(X1, y, rcond=None)
        res = y - X1 @ coef
        return 1 - res.var() / y.var()
    a, b, c = r2([xg]), r2([xg, xc]), r2([xc])
    P(f"| {SHORT[tag]} | {a:.3f} | {b:.3f} | {b - a:+.3f} | {c:.3f} | {b - c:+.3f} |")
