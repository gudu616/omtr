def partial_spearman(x, y, z):
    """rank-residual partial Spearman (same fn as harness/followup_analysis.py)."""
    rx, ry, rz = rankdata(x), rankdata(y), rankdata(z)
    def resid(a, b):
        b1 = np.column_stack([np.ones_like(b), b])
        coef, *_ = np.linalg.lstsq(b1, a, rcond=None)
        return a - b1 @ coef
    r, p = spearmanr(resid(rx, rz), resid(ry, rz))
    return float(r), float(p)


def fisher_z(r):
    r = min(max(r, -0.999999), 0.999999)
    return 0.5 * math.log((1 + r) / (1 - r))


def z_diff(r1, n1, r2, n2, corr=1.06):
    """Fisher-z difference test with Spearman SE correction (Fieller/Bonett-Wright)."""
    se = math.sqrt(corr / (n1 - 3) + corr / (n2 - 3))
    z = (fisher_z(r1) - fisher_z(r2)) / se
    return z, 2 * (1 - norm.cdf(abs(z))), se


def rank_biserial(a, b):
    """rank-biserial for a vs b: positive means a > b (matches harness convention check)."""
    u, _ = mannwhitneyu(a, b, alternative="two-sided")
    return 2 * u / (len(a) * len(b)) - 1


